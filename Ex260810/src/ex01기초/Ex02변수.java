package ex01기초;

public class Ex02변수 {

	public static void main(String[] args) {

		// 한줄 삭제 : ctrl+D
		
		// 변수 선언
		int num = 7;
		
		System.out.println(num);
		
		// 할당
		num = 10;
		System.out.println(num);
		// 재할당
		
		num = 20;
		System.out.println(num);
		
		// 상수
		final double PI = 3.14;
		final float PI2 = 3.14f;
		
		System.out.println(PI);
		System.out.println(PI2);
		
		
		
		
	}

}
