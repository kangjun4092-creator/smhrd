package ex02반복문;

import java.util.Scanner;

public class Ex01for문 {

	public static void main(String[] args) {
		
		
		
		
		
		// 변하지 않는 부분 : 2, *, =   (문자열 출력)
		// 변하는 부분 : 곱해지는 값, 연산한 값  => 반복문
		
		for (int i=1;i<=9;i++) {
			System.out.println("2"+"*"+i+"="+(2*i));
		}
		
		
		
		
		
		
	}

}
