package ex02반복문;

public class Ex03이중for문 {

	public static void main(String[] args) {

		// 이중 for문 : for문 안에 for문이 있는 구조!
		
		
		//1. for문 사용해서 숫자 1~4까지 반복하기
		
		for(int i=1;i<5;i++) {
			System.out.print(i+" ");
			// 2. for문을 사용해서 !~3까지 반복하기
			for(int j=1;j<4;j++) {
				System.out.print(j+" ");
			}System.out.println(" ");
		}
		
		
		
		
		
		
		
	}

}
