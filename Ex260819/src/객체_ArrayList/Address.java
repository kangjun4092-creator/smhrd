package 객체_ArrayList;

public class Address {

	
	// 전화번호부 설계도 클래스
	
	// 1. 필드
	private String name;
	private int age;
	private String tel;
	
	
	// 2. 메소드 -> 생성자메소드, getter메소드
	public Address(String name, int age, String tel) {
		super();
		this.name = name;
		this.age = age;
		this.tel = tel;
	}
	public String getName() {
		return name;
	}
	public int getAge() {
		return age;
	}
	public String getTel() {
		return tel;
	}
	
	
	
	
	
	
	
	
	
	
	
	
	
	
	
	
	
	
}
